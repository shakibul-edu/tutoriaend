"""
seo/serializers.py
==================
Minimal, read-only serializers that expose ONLY what a Next.js sitemap
or ISR (Incremental Static Regeneration) page generator actually needs.

Design decisions
----------------
* No ModelSerializer for lists that only return 2–3 fields.
  Calling ModelSerializer on 100 k rows allocates a validator chain,
  many internal dicts, and lots of Python objects.  Plain Serializer
  (or even direct .values()) is 3–5× faster in profiling.

* `updated_at` is included on the tutor endpoint so Next.js can set
  <lastmod> in the sitemap and decide whether to revalidate a page.

* Subject / class (Grade) slug is derived with Django's slugify at
  read time — slugs are stable and cheap for small tables (< 1 000 rows).

* Location serializer works from pre-stored location_slug /
  location_name columns on CustomUser — no reverse-geocoding at runtime.
"""

from rest_framework import serializers
from django.utils.text import slugify


# --------------------------------------------------------------------------
# Tutor (TeacherProfile)
# --------------------------------------------------------------------------

class SeoTutorSerializer(serializers.Serializer):
    """
    Returns just slug + updated_at — all a sitemap needs.

    Why Serializer not ModelSerializer:
      At 100 k rows ModelSerializer adds ~40 % overhead from field
      introspection.  Using a plain Serializer with explicit fields
      avoids that entirely.
    """
    slug = serializers.SlugField()
    updated_at = serializers.DateTimeField()


# --------------------------------------------------------------------------
# Location
# --------------------------------------------------------------------------

class SeoLocationSerializer(serializers.Serializer):
    """
    Works from CustomUser.location_name / location_slug columns that
    are set via the management command (populate_location_slugs) or
    whenever a user updates their profile location.

    Both fields are stored, so this endpoint makes zero external calls.
    """
    location_name = serializers.CharField()
    location_slug = serializers.SlugField()


# --------------------------------------------------------------------------
# Subject
# --------------------------------------------------------------------------

class SeoSubjectSerializer(serializers.Serializer):
    """
    subject_slug is derived on-the-fly from the name because Subject
    is a small table and slugifying at read time costs nothing.
    Storing the slug separately would require another migration.
    """
    id = serializers.IntegerField()
    name = serializers.CharField()
    subject_slug = serializers.SerializerMethodField()

    def get_subject_slug(self, obj) -> str:
        # obj is a dict from .values() so we access by key
        return slugify(obj['name'])


# --------------------------------------------------------------------------
# Class (Grade)
# --------------------------------------------------------------------------

class SeoClassSerializer(serializers.Serializer):
    """
    Same pattern as Subject — Grade is tiny so we slugify at runtime.
    """
    id = serializers.IntegerField()
    name = serializers.CharField()
    class_slug = serializers.SerializerMethodField()

    def get_class_slug(self, obj) -> str:
        return slugify(obj['name'])


# --------------------------------------------------------------------------
# Subject × Location pages  (for /tutor/[subject]/[location] routes)
# --------------------------------------------------------------------------

class SeoSubjectLocationSerializer(serializers.Serializer):
    """
    Represents a unique (subject_slug, location_slug) pair.
    Next.js uses these to pre-generate every combination as a static page.

    Generated by a DB query that joins TeacherProfile → subject_list →
    Subject and TeacherProfile → user → CustomUser.location_slug,
    then runs DISTINCT so we don't return duplicates.
    """
    subject_name = serializers.CharField()
    subject_slug = serializers.CharField()
    location_name = serializers.CharField()
    location_slug = serializers.CharField()
    tutor_count = serializers.IntegerField(
        help_text='Number of tutors covering this combination. Useful for deciding whether to index the page.'
    )


# --------------------------------------------------------------------------
# Class × Location pages  (for /tutor/[class]/[location] routes)
# --------------------------------------------------------------------------

class SeoClassLocationSerializer(serializers.Serializer):
    """
    Same idea as SubjectLocation but keyed on Grade (class).
    """
    class_name = serializers.CharField()
    class_slug = serializers.CharField()
    location_name = serializers.CharField()
    location_slug = serializers.CharField()
    tutor_count = serializers.IntegerField()


# --------------------------------------------------------------------------
# Detailed Tutor (for public tutor profile page)
# --------------------------------------------------------------------------

class SeoTutorSubjectSerializer(serializers.Serializer):
    """
    Serializer for subjects taught by a tutor.
    """
    id = serializers.IntegerField()
    name = serializers.CharField()
    subject_slug = serializers.SerializerMethodField()

    def get_subject_slug(self, obj) -> str:
        return slugify(obj.name)


class SeoTutorDetailSerializer(serializers.Serializer):
    """
    Returns the basic public details of a tutor for dynamic programmatic pages.
    """
    name = serializers.SerializerMethodField()
    bio = serializers.CharField(allow_null=True)
    profile_picture = serializers.SerializerMethodField()
    verified = serializers.BooleanField()
    highest_qualification = serializers.CharField()
    teaching_mode = serializers.CharField()
    starting_salary = serializers.IntegerField(source='min_salary')
    rating = serializers.SerializerMethodField()
    review_count = serializers.SerializerMethodField()
    subjects_taught = SeoTutorSubjectSerializer(many=True, source='subject_list')

    def get_name(self, obj) -> str:
        if obj.user:
            return (obj.user.get_full_name() or obj.user.username).strip()
        return ""

    def get_profile_picture(self, obj) -> str:
        if obj.profile_picture:
            return obj.profile_picture.url
        return None

    def get_rating(self, obj) -> float:
        if hasattr(obj, 'rating'):
            return obj.rating
        from base.utils import get_average_review
        rating, _ = get_average_review(obj)
        return rating

    def get_review_count(self, obj) -> int:
        if hasattr(obj, 'review_count'):
            return obj.review_count
        from base.utils import get_average_review
        _, count = get_average_review(obj)
        return count

